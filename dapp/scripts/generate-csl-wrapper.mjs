// generate-csl-wrapper.mjs
// 把 cardano_serialization_lib_bg.wasm 转 base64，生成 src/csl-wrapper.js（同步初始化）
// 运行：node scripts/generate-csl-wrapper.mjs
// 原理：SDK(CJS) 同步 require serialization-lib，wrapper 不能有 top-level await / 同步XHR(arraybuffer受限)，
//       base64 内联 + atob 同步解码 + new WebAssembly.Instance 同步实例化
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const wasmPath = join(
  root,
  'node_modules/@emurgo/cardano-serialization-lib-browser/cardano_serialization_lib_bg.wasm'
)
const outPath = join(root, 'src/csl-wrapper.js')

const b64 = readFileSync(wasmPath).toString('base64')

const content = `// GENERATED by scripts/generate-csl-wrapper.mjs — DO NOT EDIT
// 同步初始化 wasm-bindgen(--target web)：base64 内联 + atob + new WebAssembly.Instance
// SDK(CJS) 同步 require 本模块，故不能使用 top-level await 或异步 fetch
import * as bg from '@emurgo/cardano-serialization-lib-browser/cardano_serialization_lib_bg.js'

const B64 = '${b64}'
const bytes = Uint8Array.from(atob(B64), (c) => c.charCodeAt(0))
const module = new WebAssembly.Module(bytes)
const instance = new WebAssembly.Instance(module, {
  './cardano_serialization_lib_bg.js': bg,
})
bg.__wbg_set_wasm(instance.exports)

export * from '@emurgo/cardano-serialization-lib-browser/cardano_serialization_lib_bg.js'
`

writeFileSync(outPath, content)
console.log(`✓ ${outPath} (${(b64.length / 1024 / 1024).toFixed(2)} MB base64)`)
